void MX_SPI1_Init(void) {
    /* Disabled: SPI1 pins PA5/PA6/PA7 conflict with motor pins. */
    __HAL_RCC_SPI1_CLK_DISABLE();
    return;

    __HAL_RCC_SPI1_CLK_ENABLE();
    __HAL_RCC_GPIOA_CLK_ENABLE();
    
    GPIO_InitTypeDef gpio = {0};
    gpio.Pin = GPIO_PIN_5 | GPIO_PIN_7;  // SCK, MOSI
    gpio.Mode = GPIO_MODE_AF_PP;
    gpio.Speed = GPIO_SPEED_FREQ_HIGH;
    HAL_GPIO_Init(GPIOA, &gpio);
    
    gpio.Pin = GPIO_PIN_6;  // MISO
    gpio.Mode = GPIO_MODE_INPUT;
    HAL_GPIO_Init(GPIOA, &gpio);
    
    // 简单配置 SPI1 为主模式
    SPI1->CR1 = SPI_CR1_MSTR | SPI_CR1_SSI | SPI_CR1_SSM | SPI_CR1_SPE | (0 << 3);
    SPI1->CR1 |= SPI_CR1_DFF; // 16-bit 可选
    
    UART_Printf("SPI1 CR1 = 0x%04X\r\n", SPI1->CR1);
}

